def read_and_preprocess_image(image_path, target_size=IMAGE_SIZE):
    """
    Reads an image, converts it to grayscale, resizes it, and normalizes pixel values.
    Args:
        image_path (str): Path to the image file.
        target_size (tuple): Desired (width, height) for the resized image.
    Returns:
        np.ndarray: Preprocessed image as a float64 NumPy array with values [0, 1].
                    Returns None if the image cannot be read.
    """
    try:
        # Read image in grayscale
        img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
        if img is None:
            print(f"Warning: Could not read image {image_path}. Skipping.")
            return None

        # Resize image
        img = cv2.resize(img, target_size, interpolation=cv2.INTER_AREA)

        # Normalize pixel values to [0, 1]
        img = img.astype(np.float64) / 255.0

        return img
    except Exception as e:
        print(f"Error processing image {image_path}: {e}. Skipping.")
        return None

def save_image(image_array, output_path):
    """
    Saves an image to the specified path.
    Args:
        image_array (np.ndarray): Image data (float64, [0,1]) to save.
        output_path (str): Full path including filename and extension to save the image.
    """
    try:
        # Convert back to uint8 [0, 255] before saving with OpenCV
        img_to_save = (image_array * 255).astype(np.uint8)
        cv2.imwrite(output_path, img_to_save)
    except Exception as e:
        print(f"Error saving image to {output_path}: {e}")

def calculate_metrics(original_img, noisy_img, denoised_img):
    """
    Calculates image quality metrics (Mean, Median, Std Dev, MSE, PSNR, SSIM).
    Args:
        original_img (np.ndarray): Original image (float64, [0, 1]).
        noisy_img (np.ndarray): Noisy image (float64, [0, 1]).
        denoised_img (np.ndarray): Denoised image (float64, [0, 1]).
    Returns:
        dict: A dictionary containing calculated metrics.
    """
    metrics = {}
    # Convert images to 8-bit for SSIM if they are float64, as SSIM expects uint8 by default
    # or float in a specific range and data_range specified.

    # For float [0, 1] images, set data_range=1 for SSIM and PSNR.

    # Metrics for Original Image (e.g., characteristics)
    metrics['Original_Mean'] = np.mean(original_img)
    metrics['Original_Median'] = np.median(original_img)
    metrics['Original_StdDev'] = np.std(original_img)

    # MSE: Mean Squared Error between two images
    metrics['MSE_Noisy_vs_Original'] = mean_squared_error(original_img, noisy_img)
    metrics['MSE_Denoised_vs_Original'] = mean_squared_error(original_img, denoised_img)

    # PSNR: Peak Signal-to-Noise Ratio
    # PSNR is usually calculated for image pairs with a maximum possible pixel value (e.g., 255 for uint8, 1 for float [0,1]).
    metrics['PSNR_Noisy_vs_Original'] = peak_signal_noise_ratio(original_img, noisy_img, data_range=1)
    metrics['PSNR_Denoised_vs_Original'] = peak_signal_noise_ratio(original_img, denoised_img, data_range=1)

    # SSIM: Structural Similarity Index
    # Requires data_range=1 for float images [0,1]
    metrics['SSIM_Noisy_vs_Original'] = structural_similarity(original_img, noisy_img, data_range=1)
    metrics['SSIM_Denoised_vs_Original'] = structural_similarity(original_img, denoised_img, data_range=1)

    return metrics

def process_dataset(input_root_dir, output_root_dir, image_size, noise_types, denoising_methods, supported_formats):
    """
    Processes the entire dataset: applies noise, denoises, calculates metrics, and saves results.
    Args:
        input_root_dir (str): Root directory of the input dataset.
        output_root_dir (str): Root directory for all outputs (noisy, denoised, results).
        image_size (tuple): Target size for image resizing (width, height).
        noise_types (dict): Dictionary of noise types and their functions.
        denoising_methods (dict): Dictionary of denoising methods and their functions.
        supported_formats (tuple): Tuple of supported image file extensions.
    Returns:
        pd.DataFrame: A DataFrame containing all calculated metrics and paths.
    """
    results_list = []

    # Setup output directories relative to output_root_dir
    noisy_output_dir = os.path.join(output_root_dir, 'noisy')
    denoised_output_dir = os.path.join(output_root_dir, 'denoised')

    # Ensure these specific output directories exist
    create_directories([noisy_output_dir, denoised_output_dir])

    print(f"Starting dataset processing from: {input_root_dir}")

    for class_folder in os.listdir(input_root_dir):
        class_path = os.path.join(input_root_dir, class_folder)
        if not os.path.isdir(class_path):
            continue

        print(f"Processing class: {class_folder}")

        for image_name in os.listdir(class_path):
            if not image_name.lower().endswith(supported_formats):
                print(f"Skipping unsupported file: {image_name}")
                continue

            original_image_path = os.path.join(class_path, image_name)
            base_name = os.path.splitext(image_name)[0]

            original_img = read_and_preprocess_image(original_image_path, image_size)
            if original_img is None:
                continue

            for noise_name, noise_func in noise_types.items():
                print(f"  Applying {noise_name} noise to {image_name}")
                noisy_img = noise_func(original_img)

                # Save noisy image
                noisy_image_filename = f"{base_name}_{noise_name}_noisy.png"
                noisy_image_path = os.path.join(noisy_output_dir, noisy_image_filename)
                save_image(noisy_img, noisy_image_path)

                for method_name, denoise_func in denoising_methods.items():
                    print(f"    Denoising with {method_name}")
                    denoised_img = denoise_func(noisy_img)

                    # Save denoised image
                    denoised_image_filename = f"{base_name}_{noise_name}_{method_name}_denoised.png"
                    denoised_image_path = os.path.join(denoised_output_dir, denoised_image_filename)
                    save_image(denoised_img, denoised_image_path)

                    # Calculate metrics
                    metrics = calculate_metrics(original_img, noisy_img, denoised_img)

                    row = {
                        'Image Name': image_name,
                        'Class': class_folder,
                        'Noise Type': noise_name,
                        'Denoising Method': method_name,
                        **metrics,
                        'Noisy Image Path': noisy_image_path,
                        'Denoised Image Path': denoised_image_path
                    }
                    results_list.append(row)

    print("Dataset processing complete.")
    return pd.DataFrame(results_list)

