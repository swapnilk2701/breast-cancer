import matplotlib.pyplot as plt

def display_sample_images(original_img, noisy_img, denoised_img, title_suffix=""):
    """
    Displays original, noisy, and denoised images side-by-side.
    Args:
        original_img (np.ndarray): Original image (float64, [0, 1]).
        noisy_img (np.ndarray): Noisy image (float64, [0, 1]).
        denoised_img (np.ndarray): Denoised image (float64, [0, 1]).
        title_suffix (str): Additional text for the plot title.
    """
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    axes[0].imshow(original_img, cmap='gray')
    axes[0].set_title('Original Image')
    axes[0].axis('off')

    axes[1].imshow(noisy_img, cmap='gray')
    axes[1].set_title(f'Noisy Image {title_suffix}')
    axes[1].axis('off')

    axes[2].imshow(denoised_img, cmap='gray')
    axes[2].set_title(f'Denoised Image {title_suffix}')
    axes[2].axis('off')

    plt.tight_layout()
    plt.show()

def plot_metrics_comparison(df, metric_name, title, y_label, save_path=None):
    """
    Generates comparison plots for specified metrics (e.g., PSNR, SSIM).
    Args:
        df (pd.DataFrame): DataFrame containing the results.
        metric_name (str): Name of the metric column to plot (e.g., 'PSNR_Denoised_vs_Original').
        title (str): Title of the plot.
        y_label (str): Label for the Y-axis.
        save_path (str, optional): Path to save the plot. If None, plot is not saved.
    """
    plt.figure(figsize=(12, 6))

    # Group by 'Noise Type' and 'Denoising Method' and calculate the mean of the metric
    plot_data = df.groupby(['Noise Type', 'Denoising Method'])[metric_name].mean().unstack()

    plot_data.plot(kind='bar', figsize=(15, 7))
    plt.title(title)
    plt.xlabel('Noise Type')
    plt.ylabel(y_label)
    plt.xticks(rotation=45, ha='right')
    plt.legend(title='Denoising Method', bbox_to_anchor=(1.05, 1), loc='upper left')
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path)
        print(f"Plot saved to: {save_path}")
    plt.show()

