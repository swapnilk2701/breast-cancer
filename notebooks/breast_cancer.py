def wiener_filter(img):
    """Applies a Wiener filter using scikit-image's implementation.
    For simplicity, psf (point spread function) can be left None for a non-blind deconvolution.
    """
    dummy_psf = gf_ndimage(np.zeros((3,3)), 1, output=None, mode='constant')
    dummy_psf[1,1] = 1 # make a point spread function for deblurring example
    # Normalise it
    dummy_psf /= dummy_psf.sum()

    # Apply Wiener filter. The `balance` parameter (default 0.5) balances inverse filtering with noise smoothing.
    # For pure denoising, a lower `balance` value might be more appropriate if we don't have strong blurring.
    denoised_img = wiener(img, dummy_psf, balance=0.1) # Adjusted balance for more noise reduction emphasis
    return denoised_img

def anscombe_wiener_denoising(img):
    """Applies Anscombe transform, then Wiener filter, then inverse Anscombe transform."""
    transformed_img = anscombe(img) # Use custom anscombe

    # Use the existing wiener_filter function
    denoised_transformed_img = wiener_filter(transformed_img)

    denoised_img = inverse_anscombe(denoised_transformed_img) # Use custom inverse_anscombe
    return np.clip(denoised_img, 0, 1)

def adaptive_median_filter(img, s_max=7):
    """
    Applies an adaptive median filter.
    s_max: maximum window size.
    """
    img_uint8 = (img * 255).astype(np.uint8)
    H, W = img_uint8.shape
    out = np.copy(img_uint8)

    for i in range(H):
        for j in range(W):
            s = 3 # initial window size
            while s <= s_max:
                half_s = s // 2
                r_min, r_max = max(0, i - half_s), min(H, i + half_s + 1)
                c_min, c_max = max(0, j - half_s), min(W, j + half_s + 1)
                window = img_uint8[r_min:r_max, c_min:c_max]

                if window.size == 0:
                    s += 2
                    continue

                med = np.median(window)
                z_min = np.min(window)
                z_max = np.max(window)

                pixel_val = img_uint8[i, j]

                if z_min < med < z_max: # If median is not an impulse
                    if z_min < pixel_val < z_max: # If pixel is not an impulse
                        out[i, j] = pixel_val
                    else: # Pixel is an impulse
                        out[i, j] = med
                    break
                else: # Median is an impulse, increase window size
                    s += 2
                    if s > s_max: # Max window size reached, use median
                        out[i, j] = med
                        break
    return out.astype(np.float64) / 255.0

def kuan_filter(img, win_size=5, noise_var_estimate=0.04):
    """
    Applies the Kuan filter for speckle noise reduction.
    img: float64 [0,1] image.
    win_size: window size for local statistics.
    noise_var_estimate: estimated variance of the speckle noise (e.g., from NOISE_TYPES['speckle'] var).
    """
    local_mean = uniform_filter(img, size=win_size)
    local_sq_mean = uniform_filter(img**2, size=win_size)
    local_variance = local_sq_mean - local_mean**2

    # Clamp local_variance to avoid division by zero
    local_variance[local_variance < 1e-6] = 1e-6

    # Kuan filter coefficient (B)
    B = 1 - (noise_var_estimate / local_variance)
    B[B < 0] = 0 # Clamp B to be non-negative

    denoised_img = local_mean + B * (img - local_mean)
    return np.clip(denoised_img, 0, 1)

